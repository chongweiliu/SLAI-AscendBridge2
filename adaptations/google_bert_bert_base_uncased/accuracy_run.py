"""
Benchmark accuracy_run.py for google-bert/bert-base-uncased (Masked LM).
Generated by benchmark-runner. Dimension 2 (accuracy .pt) + 3 (perf) + 4 (trace, required).

两步依次执行:
  Step 1: 单样本 -> trace_*.json + benchmark_metrics_*.json (性能分析)
  Step 2: 全样本 -> outputs_*.pt (精度测试)

MLM (非生成式) 画像方式: [MASK] 填空 + 伪困惑度 (pseudo-perplexity)
  - 对每条文本确定性地随机掩盖 ~15% 的非特殊 token (固定种子，可复现)
  - forward 后在 [MASK] 位置取 argmax 预测原词并还原句子 (填空画像)
  - 在 [MASK] 位置对原始 token 计算交叉熵 -> exp(loss) 即伪困惑度
  - 同时保存首个 [MASK] 位置的完整 logits (用于 CUDA/NPU 算子精度对比)

Usage:
    uv run python accuracy_run.py                    # 完整执行 (step1 -> step2, config 随机权重)
    uv run python accuracy_run.py --use-pretrained   # Tier2: 加载预训练权重
    uv run python accuracy_run.py --cpu              # 强制 CPU 推理 (禁用 NPU/CUDA)

Model Type: masked_lm (encoder, non-generative)
Recommended Dataset: wikitext (缺失时降级内置文本)

Host notes (2x Ascend910, 多 runner 并发):
- 本机严禁设置 ASCEND_RT_VISIBLE_DEVICES（会导致 aclInit error 107001）；
  选卡一律通过 torch.npu.mem_get_info() 挑空闲卡 + torch.npu.set_device()。
"""

