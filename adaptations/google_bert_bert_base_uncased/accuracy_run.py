def get_device(force_cpu: bool = False):
    """获取推理设备。若 force_cpu=True，强制返回 CPU。

    默认优先级: NPU > CUDA > CPU
    NPU 选卡: 用 torch.npu.mem_get_info() 遍历各卡，选空闲（free 显存最大）的卡。
    本机严禁设置 ASCEND_RT_VISIBLE_DEVICES，选卡一律用 torch.npu.set_device()。
    """
    if force_cpu:
        return "cpu", 0, "cpu"

    try:
        import torch_npu  # noqa: F401

        if hasattr(torch, "npu") and torch.npu.is_available():
            count = torch.npu.device_count()
            best_index = 0
            best_free = -1
            for i in range(count):
                try:
                    free, total = torch.npu.mem_get_info(i)
                except Exception:
                    free, total = 0, 0
                print(f"[Device] NPU {i}: free={free / 1024**3:.2f}GB / total={total / 1024**3:.2f}GB")
                if free > best_free:
                    best_free = free
                    best_index = i
            print(f"[Device] Huawei Ascend NPU detected; selected idle device npu:{best_index}")
            torch.npu.set_device(best_index)
            device_name = torch.npu.get_device_name(best_index)
            return f"npu:{best_index}", count, device_name
    except ImportError:
        pass

    if torch.cuda.is_available():
        device_name = torch.cuda.get_device_name(0)
        return "cuda:0", torch.cuda.device_count(), device_name
    return "cpu", 0, "cpu"


class _PerfMonitor:
    """性能监控器：测量推理延迟和峰值内存"""

    def __init__(self, device_type, device_ids=None):
        self.device_type = device_type
        self.device_ids = device_ids
        self.start = None
        self.latency_s = None
        self.peak_memory_mb = None

    def __enter__(self):
        if self.device_type == "npu":
            import torch_npu  # noqa: F401

            torch.npu.synchronize()
            if self.device_ids is not None:
                for dev_id in self.device_ids:
                    torch.npu.reset_peak_memory_stats(dev_id)
            else:
                torch.npu.reset_peak_memory_stats()
        elif self.device_type == "cuda":
            torch.cuda.synchronize()
            if self.device_ids is not None:
                for dev_id in self.device_ids:
                    torch.cuda.reset_peak_memory_stats(dev_id)
            else:
                torch.cuda.reset_peak_memory_stats()

        self.start = time.perf_counter()
        return self

    def __exit__(self, *args):
        if self.device_type == "npu":
            import torch_npu  # noqa: F401

            torch.npu.synchronize()
            if self.device_ids is not None:
                max_mem = 0.0
                for dev_id in self.device_ids:
                    mem = torch.npu.max_memory_allocated(dev_id)
                    max_mem = max(max_mem, mem)
                self.peak_memory_mb = max_mem / (1024**2)
            else:
                self.peak_memory_mb = torch.npu.max_memory_allocated() / (1024**2)
        elif self.device_type == "cuda":
            torch.cuda.synchronize()
            if self.device_ids is not None:
                max_mem = 0.0
                for dev_id in self.device_ids:
                    mem = torch.cuda.max_memory_allocated(dev_id)
                    max_mem = max(max_mem, mem)
                self.peak_memory_mb = max_mem / (1024**2)
            else:
                self.peak_memory_mb = torch.cuda.max_memory_allocated() / (1024**2)
        else:
            self.peak_memory_mb = 0.0

        self.latency_s = time.perf_counter() - self.start
        return False


def get_profiler_context(device_short):
    """根据硬件动态返回原生 Profiler 上下文"""
    if device_short == "npu":
        import torch_npu  # noqa: F401
        from torch_npu.profiler import ProfilerActivity as NPUActivity
        from torch_npu.profiler import profile as npu_profile

        activities = [NPUActivity.CPU, NPUActivity.NPU]
        return npu_profile(activities=activities, record_shapes=True, profile_memory=True, with_stack=True)
    else:
        activities = [torch.profiler.ProfilerActivity.CPU]
        if device_short == "cuda":
            activities.append(torch.profiler.ProfilerActivity.CUDA)

        return torch.profiler.profile(activities=activities, record_shapes=True, profile_memory=True, with_stack=True)


def get_dtype_str(dtype: torch.dtype) -> str:
    """Convert torch dtype to short string (fp32, fp16, bf16)."""
    dtype_map = {
        torch.float32: "fp32",
        torch.float16: "fp16",
        torch.bfloat16: "bf16",
        torch.int64: "int64",
        torch.int32: "int32",
    }
    return dtype_map.get(dtype, str(dtype).replace("torch.", ""))


def get_package_versions() -> dict:
    """获取关键依赖包的版本"""
    import importlib.metadata

    packages = ["torch", "transformers", "torch_npu", "numpy", "datasets"]
    versions = {}
    for pkg in packages:
        try:
            versions[pkg] = importlib.metadata.version(pkg)
        except importlib.metadata.PackageNotFoundError:
            versions[pkg] = "not_installed"
    return versions


def setup_model(use_pretrained: bool, device, cache_dir: str):
    """加载模型 (MaskedLM / BERT)"""
    MODEL_ID = "google-bert/bert-base-uncased"

    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, cache_dir=cache_dir)
    config = AutoConfig.from_pretrained(MODEL_ID, cache_dir=cache_dir)

    if use_pretrained:
        model = AutoModelForMaskedLM.from_pretrained(MODEL_ID, cache_dir=cache_dir)
        model = model.to(device)
    else:
        model = AutoModelForMaskedLM.from_config(config)
        model = model.to(device)
    model.eval()

    return model, tokenizer


def build_masked_inputs(tokenizer, text: str, sample_index: int, device):
    """对单条文本做确定性 [MASK] 掩盖，返回 (inputs, selected_positions, original_ids)。

    - 仅掩盖非特殊 token（[CLS]/[SEP]/[PAD] 不参与）
    - 使用固定种子 (MASK_SEED_BASE + sample_index) 保证多次运行完全一致
    - 至少掩盖 1 个 token；若文本无可掩盖 token 返回 None
    """
    orig = tokenizer(text, return_tensors="pt", truncation=True, max_length=512)
    original_ids = orig["input_ids"]  # [1, L]

    special_ids = {tokenizer.cls_token_id, tokenizer.sep_token_id, tokenizer.pad_token_id}
    candidates = torch.ones(original_ids.shape[1], dtype=torch.bool)
    for sp in special_ids:
        if sp is not None:
            candidates &= original_ids[0] != sp
    cand_positions = candidates.nonzero(as_tuple=True)[0]
    if cand_positions.numel() == 0:
        return None, None, None

    gen = torch.Generator()
    gen.manual_seed(MASK_SEED_BASE + sample_index)
    rand_vals = torch.rand(cand_positions.numel(), generator=gen)
    selected = cand_positions[rand_vals < MASK_RATIO]
    if selected.numel() == 0:
        selected = cand_positions[:1]

    masked_ids = original_ids.clone()
    masked_ids[0, selected] = tokenizer.mask_token_id

    inputs = {k: v.to(device) for k, v in orig.items()}
    inputs["input_ids"] = masked_ids.to(device)
    return inputs, selected, original_ids


def run_step1(model, tokenizer, first_device, device_short, device_tag, device_ids, mode_str, adapt_dir: Path, dataset_name: str, texts: list[str]):
    """Step 1: 单样本推理 -> trace_*.json + benchmark_metrics_*.json"""
    print("\n" + "=" * 60)
    print("Step 1: 单样本推理 (性能分析)")
    print("=" * 60)

    model_dtype = next(model.parameters()).dtype
    dtype_str = get_dtype_str(model_dtype)

    trace_path = adapt_dir / f"trace_{device_tag}_{dtype_str}_{mode_str}_{dataset_name}.json"
    metrics_path = adapt_dir / f"benchmark_metrics_{device_tag}_{dtype_str}_{mode_str}_{dataset_name}.json"

    # 单样本（空数据集时使用 fallback）
    text = texts[0] if texts else "The capital of France is Paris."
    built = build_masked_inputs(tokenizer, text, 0, first_device)
    if built[0] is None:
        inputs, _, _ = build_masked_inputs(tokenizer, "The capital of France is Paris.", 0, first_device)
    else:
        inputs = built[0]

    profiler_context = get_profiler_context(device_short)

    start_time = datetime.now().isoformat()
    with profiler_context as prof:
        with _PerfMonitor(device_short, device_ids) as m:
            with torch.no_grad():
                out = model(**inputs)
                _ = out.logits  # MLM: logits over vocab at every position

        latency_s = m.latency_s
        peak_memory_mb = m.peak_memory_mb

    # 导出 trace
    prof.export_chrome_trace(str(trace_path))

    # 获取实际设备型号
    device_model = "unknown"
    if device_short == "npu" and first_device.index is not None:
        device_model = torch.npu.get_device_name(first_device.index)
    elif device_short == "cuda" and first_device.index is not None:
        device_model = torch.cuda.get_device_name(first_device.index)

    # 写入 metrics（end_time / ttft_ms / tpot_ms 将在 main() 末尾更新）
    metrics = {
        "start_time": start_time,
        "latency_s": round(latency_s, 6),
        "peak_memory_mb": round(peak_memory_mb, 2),
        "num_samples": len(texts),
        "device": str(first_device),
        "device_model": device_model,
        "mode": mode_str,
        "dataset": dataset_name,
        "dtype": dtype_str,
        "output_type": "generated_text",
        "packages": get_package_versions(),
    }
    metrics_path.write_text(json.dumps(metrics, indent=2))

    # 清理临时目录（忽略错误，NPU profiler 可能留下文件）
    prof_dir = adapt_dir / "export_only_prof_dir"
    if prof_dir.exists():
        shutil.rmtree(prof_dir, ignore_errors=True)
        print(f"[benchmark] cleaned up {prof_dir}")

    print(f"[benchmark] trace saved to {trace_path}")
    print(f"[benchmark] metrics saved to {metrics_path}")
    print(f"[benchmark] {metrics}")

    return trace_path, metrics_path, start_time


def run_step2(model, tokenizer, first_device, device_short, mode_str, adapt_dir: Path, dataset_name: str, texts: list[str], max_samples: int = 250):
    """Step 2: 全样本推理 -> outputs_*.pt (MaskedLM, 非生成式)

    MLM 模型不测量 TTFT/TPOT，返回 None。

    画像方式:
    - [MASK] 填空: 掩盖 ~15% token 后 argmax 还原，保存填充后的文本
    - 伪困惑度: [MASK] 位置对原始 token 的交叉熵取 exp
    - logits: 首个 [MASK] 位置的完整 logits（算子精度对比用）

    内存优化：
    - 每个样本处理完后立即移动到 CPU
    - 每 32 个样本清理 NPU/CUDA 缓存
    - 默认限制样本数为 250（避免产出文件过大）

    输出格式 (outputs_*.pt, dict):
    - generated_text: [MASK] 填充还原后的文本列表
    - logits: 每样本首个 [MASK] 位置的 logits 张量列表
    - perplexity: 每样本伪困惑度列表

    Returns:
        tuple: (outputs_path, ttft_avg, tpot_avg) - MLM 模型 ttft_avg=None, tpot_avg=None
    """
    print("\n" + "=" * 60)
    print("Step 2: 全样本推理 (精度测试: [MASK] 填空 + 伪困惑度)")
    print("=" * 60)

    model_dtype = next(model.parameters()).dtype
    dtype_str = get_dtype_str(model_dtype)

    outputs_path = adapt_dir / f"outputs_{device_short}_{dtype_str}_{mode_str}_{dataset_name}.pt"

    # 限制样本数（R1 规则：最多 250 个样本）
    texts = texts[:max_samples]
    print(f"[benchmark] {len(texts)} samples to process (max {max_samples})")

    all_filled_texts = []
    all_logits = []
    all_ppl = []

    with torch.no_grad():
        for i, text in enumerate(texts):
            inputs, selected, original_ids = build_masked_inputs(tokenizer, text, i, first_device)
            if inputs is None:
                print(f"[benchmark] sample {i} has no maskable tokens, skipped")
                continue

            out = model(**inputs)
            logits = out.logits  # [1, L, V]

            mask_logits = logits[0, selected]  # [M, V]
            targets = original_ids[0, selected].to(first_device)  # [M]
            loss = F.cross_entropy(mask_logits, targets)
            ppl = torch.exp(loss).item()
            all_ppl.append(ppl)

            # [MASK] 填空: argmax 预测原词并还原句子
            pred_ids = mask_logits.argmax(dim=-1).cpu()
            filled_ids = original_ids.clone()
            filled_ids[0, selected] = pred_ids
            filled_text = tokenizer.decode(filled_ids[0], skip_special_tokens=True)
            all_filled_texts.append(filled_text)

            # 首个 [MASK] 位置完整 logits（CUDA/NPU 算子精度对比用）
            first_mask_logits = logits[0, selected[0]].cpu()
            all_logits.append(first_mask_logits)

            del out, logits, mask_logits, inputs

            # 每 32 个样本清理缓存（更频繁以避免 OOM）
            if (i + 1) % 32 == 0:
                if device_short == "npu":
                    torch.npu.empty_cache()
                elif device_short == "cuda":
                    torch.cuda.empty_cache()
                print(f"[benchmark] processed {i + 1}/{len(texts)} samples (cache cleared)")
            elif (i + 1) % 8 == 0:
                print(f"[benchmark] processed {i + 1}/{len(texts)} samples")

    # 保存 outputs（含 generated_text、logits 和 perplexity）
    output_data = {
        "generated_text": all_filled_texts,
        "logits": all_logits,
        "perplexity": all_ppl,
    }
    torch.save(output_data, outputs_path)

    ppl_avg = round(sum(all_ppl) / len(all_ppl), 2) if all_ppl else None
    print(f"[benchmark] outputs saved to {outputs_path}")
    print(f"[benchmark]   - generated_text ([MASK] filled): {len(all_filled_texts)} samples")
    if all_filled_texts:
        print(f"[benchmark]   - example: {all_filled_texts[0][:100]}")
    print(f"[benchmark]   - logits: {len(all_logits)} samples" + (f", shape: {tuple(all_logits[0].shape)}" if all_logits else ""))
    print(f"[benchmark]   - pseudo-perplexity: avg={ppl_avg}" + (f", min={min(all_ppl):.2f}, max={max(all_ppl):.2f}" if all_ppl else ""))

    return outputs_path, None, None  # MLM 不测量 TTFT/TPOT


