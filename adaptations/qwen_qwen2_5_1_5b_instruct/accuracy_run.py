def get_device(force_cpu: bool = False):
    """获取推理设备。若 force_cpu=True，强制返回 CPU。

    默认优先级: NPU > CUDA > CPU
    NPU 多卡时按 mem_get_info 自动选择空闲卡（本机严禁 ASCEND_RT_VISIBLE_DEVICES，
    一律用 torch.npu.set_device() 选卡）。
    """
    if force_cpu:
        return "cpu", 0, "cpu"

    try:
        import torch_npu  # noqa: F401

        if hasattr(torch, "npu") and torch.npu.is_available():
            count = torch.npu.device_count()
            # 自动选择空闲卡：按空闲 HBM 最大者优先
            best_index = 0
            best_free = -1
            for i in range(count):
                try:
                    free, total = torch.npu.mem_get_info(i)
                except Exception:
                    free, total = 0, 0
                print(f"[Device] NPU {i}: free={free / (1024**3):.1f} GB / total={total / (1024**3):.1f} GB")
                if free > best_free:
                    best_free = free
                    best_index = i
            torch.npu.set_device(best_index)
            device_name = torch.npu.get_device_name(best_index)
            print(f"[Device] Huawei Ascend NPU detected; selected idle device npu:{best_index} ({device_name})")
            return f"npu:{best_index}", count, device_name
    except ImportError:
        pass
    if torch.cuda.is_available():
        device_name = torch.cuda.get_device_name(0)
        return "cuda:0", torch.cuda.device_count(), device_name
    return "cpu", 0, "cpu"


class _PerfMonitor:
    """性能监控器：测量推理延迟和峰值内存"""

    def __init__(self, device_type, device_ids=None):
        self.device_type = device_type
        self.device_ids = device_ids
        self.start = None
        self.latency_s = None
        self.peak_memory_mb = None

    def __enter__(self):
        if self.device_type == "npu":
            import torch_npu  # noqa: F401

            torch.npu.synchronize()
            if self.device_ids is not None:
                for dev_id in self.device_ids:
                    torch.npu.reset_peak_memory_stats(dev_id)
            else:
                torch.npu.reset_peak_memory_stats()
        elif self.device_type == "cuda":
            torch.cuda.synchronize()
            if self.device_ids is not None:
                for dev_id in self.device_ids:
                    torch.cuda.reset_peak_memory_stats(dev_id)
            else:
                torch.cuda.reset_peak_memory_stats()

        self.start = time.perf_counter()
        return self

    def __exit__(self, *args):
        if self.device_type == "npu":
            import torch_npu  # noqa: F401

            torch.npu.synchronize()
            if self.device_ids is not None:
                max_mem = 0.0
                for dev_id in self.device_ids:
                    mem = torch.npu.max_memory_allocated(dev_id)
                    max_mem = max(max_mem, mem)
                self.peak_memory_mb = max_mem / (1024**2)
            else:
                self.peak_memory_mb = torch.npu.max_memory_allocated() / (1024**2)
        elif self.device_type == "cuda":
            torch.cuda.synchronize()
            if self.device_ids is not None:
                max_mem = 0.0
                for dev_id in self.device_ids:
                    mem = torch.cuda.max_memory_allocated(dev_id)
                    max_mem = max(max_mem, mem)
                self.peak_memory_mb = max_mem / (1024**2)
            else:
                self.peak_memory_mb = torch.cuda.max_memory_allocated() / (1024**2)
        else:
            self.peak_memory_mb = 0.0

        self.latency_s = time.perf_counter() - self.start
        return False


def get_profiler_context(device_short):
    """根据硬件动态返回原生 Profiler 上下文"""
    if device_short == "npu":
        import torch_npu  # noqa: F401
        from torch_npu.profiler import ProfilerActivity as NPUActivity
        from torch_npu.profiler import profile as npu_profile

        activities = [NPUActivity.CPU, NPUActivity.NPU]
        return npu_profile(activities=activities, record_shapes=True, profile_memory=True, with_stack=True)
    else:
        activities = [torch.profiler.ProfilerActivity.CPU]
        if device_short == "cuda":
            activities.append(torch.profiler.ProfilerActivity.CUDA)

        return torch.profiler.profile(activities=activities, record_shapes=True, profile_memory=True, with_stack=True)


def measure_streaming_generation(streamer, generation_start_time):
    """使用 TextIteratorStreamer 测量 TTFT 和 TPOT

    Args:
        streamer: TextIteratorStreamer 实例
        generation_start_time: 生成开始的时间戳 (time.perf_counter())

    Returns:
        tuple: (generated_text, ttft_ms, tpot_ms)
            - generated_text: 生成的文本
            - ttft_ms: 首字延迟（毫秒），若无 token 则为 None
            - tpot_ms: 平均每 token 生成时间（毫秒），若无后续 token 则为 None
    """
    token_times = []
    generated_text = ""

    for token in streamer:
        token_times.append(time.perf_counter())
        generated_text += token

    # 计算 TTFT（首 token 相对于生成开始的时间）
    if len(token_times) >= 1:
        ttft_ms = (token_times[0] - generation_start_time) * 1000
        if len(token_times) >= 2:
            # TPOT = (最后一个 token 时间 - 第一个 token 时间) / (token 数 - 1)
            total_time_after_first = token_times[-1] - token_times[0]
            n_tokens_after_first = len(token_times) - 1
            tpot_ms = (total_time_after_first / n_tokens_after_first) * 1000
        else:
            tpot_ms = None
    else:
        ttft_ms = None
        tpot_ms = None

    return generated_text, ttft_ms, tpot_ms


def get_dtype_str(dtype: torch.dtype) -> str:
    """Convert torch dtype to short string (fp32, fp16, bf16)."""
    dtype_map = {
        torch.float32: "fp32",
        torch.float16: "fp16",
        torch.bfloat16: "bf16",
        torch.int64: "int64",
        torch.int32: "int32",
    }
    return dtype_map.get(dtype, str(dtype).replace("torch.", ""))


def get_package_versions() -> dict:
    """获取关键依赖包的版本"""
    import importlib.metadata

    packages = ["torch", "transformers", "torch_npu", "numpy", "datasets"]
    versions = {}
    for pkg in packages:
        try:
            versions[pkg] = importlib.metadata.version(pkg)
        except importlib.metadata.PackageNotFoundError:
            versions[pkg] = "not_installed"
    return versions


def setup_model(use_pretrained: bool, device, cache_dir: str):
    """加载模型 (CausalLM)"""
    MODEL_ID = "Qwen/Qwen2.5-1.5B-Instruct"

    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID, trust_remote_code=True, cache_dir=cache_dir)
    config = AutoConfig.from_pretrained(MODEL_ID, trust_remote_code=True, cache_dir=cache_dir)

    if use_pretrained:
        # Tier2: 加载失败直接抛错终止（禁止静默降级为 config 产出伪结果）
        model = AutoModelForCausalLM.from_pretrained(
            MODEL_ID,
            trust_remote_code=True,
            torch_dtype="auto",
            cache_dir=cache_dir,
        )
        model = model.to(device)
    else:
        model = AutoModelForCausalLM.from_config(config, trust_remote_code=True)
        model = model.to(device)
    model.eval()

    return model, tokenizer


def run_step1(model, tokenizer, first_device, device_short, device_ids, mode_str, adapt_dir: Path, dataset_name: str, texts: list[str]):
    """Step 1: 单样本推理 -> trace_*.json + benchmark_metrics_*.json"""
    print("\n" + "=" * 60)
    print("Step 1: 单样本推理 (性能分析)")
    print("=" * 60)

    model_dtype = next(model.parameters()).dtype
    dtype_str = get_dtype_str(model_dtype)

    trace_path = adapt_dir / f"trace_{device_short}_{dtype_str}_{mode_str}_{dataset_name}.json"
    metrics_path = adapt_dir / f"benchmark_metrics_{device_short}_{dtype_str}_{mode_str}_{dataset_name}.json"

    # 单样本（空数据集时使用 fallback）
    text = texts[0] if texts else "Hello, benchmark."
    inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=512).to(first_device)

    profiler_context = get_profiler_context(device_short)

    start_time = datetime.now().isoformat()
    with profiler_context as prof:
        with _PerfMonitor(device_short, device_ids) as m:
            with torch.no_grad():
                out = model(**inputs)
                _ = out.logits if hasattr(out, "logits") else out[0]  # 仅推理，不保存

        latency_s = m.latency_s
        peak_memory_mb = m.peak_memory_mb

    # 导出 trace
    prof.export_chrome_trace(str(trace_path))

    # 获取实际设备型号
    device_model = "unknown"
    if device_short == "npu" and first_device.index is not None:
        device_model = torch.npu.get_device_name(first_device.index)
    elif device_short == "cuda" and first_device.index is not None:
        device_model = torch.cuda.get_device_name(first_device.index)

    # 写入 metrics（end_time / ttft_ms / tpot_ms 将在 main() 末尾更新）
    metrics = {
        "start_time": start_time,
        "latency_s": round(latency_s, 6),
        "peak_memory_mb": round(peak_memory_mb, 2),
        "num_samples": len(texts),
        "device": str(first_device),
        "device_model": device_model,
        "mode": mode_str,
        "dataset": dataset_name,
        "dtype": dtype_str,
        "output_type": "generated_text",
        "packages": get_package_versions(),
    }
    metrics_path.write_text(json.dumps(metrics, indent=2))

    # 清理临时目录（忽略错误，NPU profiler 可能留下文件）
    prof_dir = adapt_dir / "export_only_prof_dir"
    if prof_dir.exists():
        shutil.rmtree(prof_dir, ignore_errors=True)
        print(f"[benchmark] cleaned up {prof_dir}")

    print(f"[benchmark] trace saved to {trace_path}")
    print(f"[benchmark] metrics saved to {metrics_path}")
    print(f"[benchmark] {metrics}")

    return trace_path, metrics_path, start_time


def run_step2(model, tokenizer, first_device, device_short, mode_str, adapt_dir: Path, dataset_name: str, texts: list[str], max_samples: int = 250):
    """Step 2: 全样本 teacher-forcing 推理 -> outputs_*.pt (CausalLM)

    Teacher-forcing 方式: 对每条文本做单次 forward，提取 last-token logits 和 perplexity。
    不使用 generate()，避免自回归生成的巨大开销。

    输出格式 (outputs_*.pt):
    - generated_text: 输入文本（teacher-forcing 不生成新文本）
    - logits: 每个 prompt 最后一个 token 的 logits 张量列表
    - perplexity: 每个样本的 perplexity 值列表

    Returns:
        tuple: (outputs_path, None, None, wall_clock_s)
    """
    print("\n" + "=" * 60)
    print("Step 2: 全样本 teacher-forcing 推理 (last-token logits + PPL)")
    print("=" * 60)

    model_dtype = next(model.parameters()).dtype
    dtype_str = get_dtype_str(model_dtype)

    outputs_path = adapt_dir / f"outputs_{device_short}_{dtype_str}_{mode_str}_{dataset_name}.pt"

    texts = texts[:max_samples]
    print(f"[benchmark] {len(texts)} samples to process (max {max_samples})")

    # Warmup: 3 iterations to match perf script's warmup policy (symmetric)
    print("[benchmark] warmup 3 iterations...")
    warmup_text = texts[0] if texts else "Hello, benchmark."
    warmup_inputs = tokenizer(warmup_text, return_tensors="pt", truncation=True, max_length=512).to(first_device)
    with torch.no_grad():
        for _ in range(3):
            _ = model(**warmup_inputs)
    if device_short == "npu":
        torch.npu.synchronize()
    print("[benchmark] warmup done")

    all_outputs = []
    all_logits = []
    all_ppl = []

    step2_start = time.perf_counter()
    with torch.no_grad():
        for i, text in enumerate(texts):
            inputs = tokenizer(text, return_tensors="pt", truncation=True, max_length=512).to(first_device)

            out = model(**inputs)
            logits = out.logits  # [1, seq_len, vocab_size]

            # Last-token logits (for accuracy comparison)
            last_token_logits = logits[0, -1, :].cpu()
            all_logits.append(last_token_logits)

            # Perplexity: shifted cross-entropy
            labels = inputs["input_ids"]
            shift_logits = logits[..., :-1, :].contiguous()
            shift_labels = labels[..., 1:].contiguous()
            loss_fct = torch.nn.CrossEntropyLoss(reduction="mean")
            loss = loss_fct(shift_logits.view(-1, shift_logits.size(-1)), shift_labels.view(-1))
            ppl = torch.exp(loss).item()
            all_ppl.append(ppl)

            # Teacher-forcing: use input text as "generated_text"
            all_outputs.append(text)

            del inputs, out, logits

            if (i + 1) % 32 == 0:
                if device_short == "npu":
                    torch.npu.empty_cache()
                elif device_short == "cuda":
                    torch.cuda.empty_cache()
                print(f"[benchmark] processed {i + 1}/{len(texts)} samples (cache cleared)")
            elif (i + 1) % 8 == 0:
                print(f"[benchmark] processed {i + 1}/{len(texts)} samples")

    if device_short == "npu":
        torch.npu.synchronize()
    step2_wall_clock = time.perf_counter() - step2_start
    wall_clock_s = round(step2_wall_clock, 6)

    output_data = {
        "generated_text": all_outputs,
        "logits": all_logits,
        "perplexity": all_ppl,
    }
    torch.save(output_data, outputs_path)

    ppl_avg = round(sum(all_ppl) / len(all_ppl), 2) if all_ppl else None
    print(f"[benchmark] outputs saved to {outputs_path}")
    print(f"[benchmark]   - generated_text: {len(all_outputs)} samples")
    print(f"[benchmark]   - logits: {len(all_logits)} samples, shape: {all_logits[0].shape}")
    print(f"[benchmark]   - perplexity: avg={ppl_avg}" + (f", min={min(all_ppl):.2f}, max={max(all_ppl):.2f}" if all_ppl else ""))
    print(f"[benchmark]   - wall_clock_s: {wall_clock_s}")

    return outputs_path, None, None, wall_clock_s


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--use-pretrained", action="store_true", help="Tier2: load pretrained weights")
    parser.add_argument("--max-samples", type=int, default=250, help="Max samples to process (default 250, per R1 rule)")
    parser.add_argument("--cpu", action="store_true", help="Force CPU inference (disable NPU/CUDA)")
    args = parser.parse_args()

    MODEL_ID = "Qwen/Qwen2.5-1.5B-Instruct"
    CACHE_DIR = (Path(__file__).resolve().parent / "models").as_posix()
    adapt_dir = Path(__file__).resolve().parent

    # 1. Seed
    SEED = 42
    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)
    transformers_set_seed(SEED)
    device, _, _ = get_device(force_cpu=args.cpu)
    if device.startswith("npu"):
        torch.npu.manual_seed_all(SEED)
    elif device.startswith("cuda"):
        torch.cuda.manual_seed_all(SEED)

    # 开启全局确定性算法（确保 CUDA/NPU 输出一致）
    torch.use_deterministic_algorithms(True, warn_only=True)

    # 仅在非 --cpu 模式下检查设备
    if not args.cpu:
        assert device.startswith(("npu", "cuda")), f"Need NPU or CUDA, got {device}"

    # 2. Load dataset（提前截断，保证 metrics.num_samples 与实际处理样本数一致）
    texts, dataset_name = load_benchmark_texts()
    texts = texts[: args.max_samples]
    print(f"[benchmark] using dataset: {dataset_name}, samples for this run: {len(texts)}, max_samples: {args.max_samples}")

    # 3. Model
    model, processor = setup_model(args.use_pretrained, device, CACHE_DIR)

    first_device = next(model.parameters()).device
    device_short = first_device.type
    mode_str = "pretrained" if args.use_pretrained else "config"

    # 提取设备 IDs
    device_ids = None
    if hasattr(model, "hf_device_map"):
        device_ids = list(set(dev.index if hasattr(dev, "index") else dev for dev in model.hf_device_map.values()))
    elif first_device.index is not None:
        device_ids = [first_device.index]

    # Step 1: 单样本 -> trace + metrics
    trace_path, metrics_path, start_time = run_step1(model, processor, first_device, device_short, device_ids, mode_str, adapt_dir, dataset_name, texts)

    # Step 2: 全样本 -> outputs (teacher-forcing)
    outputs_path, ttft_avg, tpot_avg, wall_clock_s = run_step2(model, processor, first_device, device_short, mode_str, adapt_dir, dataset_name, texts, args.max_samples)

    # 更新 metrics 文件（添加 end_time, ttft_ms, tpot_ms, wall_clock_s, warmup_iterations）
    end_time = datetime.now().isoformat()
    with open(metrics_path, "r") as f:
        metrics = json.load(f)

    metrics["end_time"] = end_time
    metrics["ttft_ms"] = ttft_avg
    metrics["tpot_ms"] = tpot_avg
    metrics["wall_clock_s"] = wall_clock_s
    metrics["warmup_iterations"] = 3

    with open(metrics_path, "w") as f:
        json.dump(metrics, indent=2, fp=f)

    print("\n" + "=" * 60)
    print("Summary")
    print("=" * 60)
    print(f"  ✅ trace: {trace_path}")
    print(f"  ✅ metrics: {metrics_path}")
    print(f"  ✅ outputs: {outputs_path} (含 generated_text + logits + perplexity)")
    if ttft_avg is not None:
        print(f"  📊 TTFT avg: {ttft_avg} ms, TPOT avg: {tpot_avg} ms")

    print(f"\n💡 To analyze NPU fallback, run:")
    print(f"   uv run python benchmark/scripts/benchmark_tool.py trace {trace_path.name}")
    print(f"   (add -v for detailed report, -j for JSON)")
    print(f"\n💡 To compare CUDA/NPU outputs (including logits):")
    print(f"   python benchmark/scripts/benchmark_tool.py compare --adaptation qwen_qwen2_5_1_5b_instruct")


if __name__ == "__main__":
    main()
